/** Coverage per cell, 0 to 1, in the same row major order. */
export function buildLogoCoverage() {
  const cells = new Float32Array(LOGO_GRID * LOGO_GRID);
  for (let i = 0; i < cells.length; i += 1) {
    cells[i] = parseInt(LOGO_HEX[i], 16) / 15;
  }
  return cells;
}
